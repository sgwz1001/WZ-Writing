/**
 * 古典韵文体裁数据集 —— 词牌格律谱 + 其他古典文体写作模板
 *
 * 数据来源：
 *   ·《钦定词谱》（清·王奕清等奉敕编，康熙五十四年武英殿刻本）
 *   ·龙榆生《唐宋词格律》（上海古籍出版社）
 *   ·王力《诗词格律》（中华书局）
 *
 * 平仄标记约定：
 *   'p' = 平声    'z' = 仄声    '*' = 可平可仄（词谱中的「中」「⊙」）
 *   凡词谱异体较多、或历代作者于某字位出入较大者，一律标 '*'。
 *   宁可放宽，不可误判 —— 校验器只在明确标 p / z 的字位上报错。
 *
 * 一词多体者只取「正体 / 最常用体」一种，别体在 note 中简述。
 * 数据自洽性保证：
 *   1) 每个词牌 sum(sections[].sentences[].len) === totalChars
 *   2) 每句 tones.length === len（由内部构造函数 s() 从谱串直接推导）
 */

/** 平仄符号：'p'=平, 'z'=仄, '*'=可平可仄 */
export type Tone = 'p' | 'z' | '*'

export interface CiSentence {
  /** 本句字数 */
  len: number
  /** 平仄谱，长度必须等于 len */
  tones: Tone[]
  /** 本句末字是否押韵 */
  rhyme: boolean
  /** 句末标点建议 */
  punct: string
}

export interface CiSection {
  /** 段名：'上阕' | '下阕' | '单调' | '第一叠' 等 */
  name: string
  sentences: CiSentence[]
}

export interface CiPai {
  /** 唯一 id，拼音小写连字符 */
  id: string
  /** 词牌名 */
  name: string
  /** 别名 */
  alias: string[]
  /** 总字数 */
  totalChars: number
  /** 体裁分类 */
  category: '小令' | '中调' | '长调'
  /** 韵部要求描述 */
  rhymeType: string
  /** 段落 */
  sections: CiSection[]
  /** 代表作例句 */
  example: string
  /** 代表作者 */
  exampleAuthor: string
  /** 简要说明：适合表达什么情绪 / 题材 */
  note: string
}

/** 其他古典文体（乐府 / 曲 / 文言文 / 古体诗 / 赋）的轻量模板，不做严格平仄校验 */
export interface ClassicalForm {
  id: string
  name: string
  /** 大类 */
  genre: '乐府' | '曲' | '文言文' | '古体诗' | '赋'
  /** 结构说明 */
  structure: string
  /** 韵律说明 */
  rhyme: string
  /** 写作要点 */
  tips: string[]
  /** 范例片段 */
  example: string
  exampleAuthor: string
}

// ── 内部构造函数：从紧凑谱串生成句子，天然保证 tones.length === len ──

/**
 * 构造一句。
 * @param tones 紧凑谱串，如 '*zzpp'，每字符为 p / z / *
 * @param rhyme 本句末字是否押韵
 * @param punct 句末标点建议
 */
function s(tones: string, rhyme = false, punct = '，'): CiSentence {
  const arr = [...tones] as Tone[]
  return { len: arr.length, tones: arr, rhyme, punct }
}

function sec(name: string, sentences: CiSentence[]): CiSection {
  return { name, sentences }
}

