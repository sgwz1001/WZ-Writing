// ── 辅助查询函数 ──────────────────────────────────────────────

/** 按 id 精确取词牌 */
export function getCiPai(id: string): CiPai | undefined {
  return CI_PAI.find((c) => c.id === id)
}

/** 按关键词搜索词牌：匹配 名称 / 别名 / 拼音 id（均含子串即命中） */
export function searchCiPai(keyword: string): CiPai[] {
  const kw = keyword.trim().toLowerCase()
  if (!kw) return []
  return CI_PAI.filter(
    (c) =>
      c.name.toLowerCase().includes(kw) ||
      c.alias.some((a) => a.toLowerCase().includes(kw)) ||
      c.id.toLowerCase().includes(kw),
  )
}

/** 按体裁分类取词牌（小令 / 中调 / 长调） */
export function getCiPaiByCategory(category: CiPai['category']): CiPai[] {
  return CI_PAI.filter((c) => c.category === category)
}

/** 按 id 精确取其他古典文体 */
export function getClassicalForm(id: string): ClassicalForm | undefined {
  return CLASSICAL_FORMS.find((f) => f.id === id)
}

/** 按大类取其他古典文体（乐府 / 曲 / 文言文 / 古体诗 / 赋） */
export function getFormsByGenre(genre: ClassicalForm['genre']): ClassicalForm[] {
  return CLASSICAL_FORMS.filter((f) => f.genre === genre)
}
